#!/usr/bin/env bash
# ==============================================================================
# 05-grant-permissions.sh - Aplicación de Mínimo Privilegio sobre Schemas
# ==============================================================================
set -euo pipefail

echo "🔒 [PostgreSQL Init] Aplicando permisos de mínimo privilegio a roles..."

: "${INGEST_USER:?INGEST_USER es requerido}"
: "${TRANSFORM_USER:?TRANSFORM_USER es requerido}"
: "${READ_USER:?READ_USER es requerido}"

psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
-- 1. Permisos para INGEST_USER (Solo schema raw)
GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO ${INGEST_USER};
GRANT USAGE ON SCHEMA raw TO ${INGEST_USER};
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA raw TO ${INGEST_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA raw GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${INGEST_USER};
REVOKE ALL ON SCHEMA staging FROM ${INGEST_USER};
REVOKE ALL ON SCHEMA curated FROM ${INGEST_USER};

-- 2. Permisos para TRANSFORM_USER (Lee raw, administra staging y curated)
GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO ${TRANSFORM_USER};
GRANT USAGE ON SCHEMA raw, staging, curated TO ${TRANSFORM_USER};
GRANT SELECT ON ALL TABLES IN SCHEMA raw TO ${TRANSFORM_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA raw GRANT SELECT ON TABLES TO ${TRANSFORM_USER};

GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA staging TO ${TRANSFORM_USER};
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA staging TO ${TRANSFORM_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA staging GRANT ALL PRIVILEGES ON TABLES TO ${TRANSFORM_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA staging GRANT ALL PRIVILEGES ON SEQUENCES TO ${TRANSFORM_USER};

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA curated TO ${TRANSFORM_USER};
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA curated TO ${TRANSFORM_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA curated GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${TRANSFORM_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA curated GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO ${TRANSFORM_USER};

-- 3. Permisos para READ_USER (API FastAPI: SOLO lectura en curated)
GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO ${READ_USER};
GRANT USAGE ON SCHEMA curated TO ${READ_USER};
GRANT SELECT ON ALL TABLES IN SCHEMA curated TO ${READ_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA curated GRANT SELECT ON TABLES TO ${READ_USER};
REVOKE ALL ON SCHEMA raw FROM ${READ_USER};
REVOKE ALL ON SCHEMA staging FROM ${READ_USER};

SQL

echo "✅ [PostgreSQL Init] Permisos asignados exitosamente."
